import Foundation

/// Completion of one `playVideo` call: `(positionSeconds, durationSeconds, errorCode, errorMessage)`. Both numbers
/// are -1 and both strings nil for a cancelled session; a non-nil `errorCode` marks a failure. Positions are in
/// SECONDS. Blocks are Dart listeners, so they may be invoked from any thread.
public typealias PlayBlock = (Int, Int, String?, String?) -> Void

/// What the plugin instance implements; `VideoPlayerApi` forwards to it on the main thread.
protocol VideoPlayerHost: AnyObject {
    func playVideo(configJson: String, completion: @escaping PlayBlock)
    func closePlayer(completion: @escaping () -> Void)
}

/// The API Dart calls through the Objective-C runtime (bindings in `lib/src/bindings/`, generated by
/// `dart run tool/ffigen.dart` from `video_player_c/video_player_api.h`, which must match this class selector for
/// selector). The outcome comes back through a block, so a call returns at once. Every `playVideo` answers its block
/// exactly once; before the plugin registers it answers `NOT_ATTACHED`.
@objc(VideoPlayerApi)
public final class VideoPlayerApi: NSObject {
    static weak var host: VideoPlayerHost?

    @objc public static func playVideo(_ playerConfigJson: String, callback: @escaping PlayBlock) {
        onMain {
            guard let host else {
                callback(-1, -1, "NOT_ATTACHED", "video_player is not attached to an engine")
                return
            }
            host.playVideo(configJson: playerConfigJson, completion: callback)
        }
    }

    @objc public static func close(_ callback: @escaping () -> Void) {
        onMain {
            guard let host else {
                callback()
                return
            }
            host.closePlayer(completion: callback)
        }
    }

    private static func onMain(_ work: @escaping () -> Void) {
        if Thread.isMainThread { work() } else { DispatchQueue.main.async(execute: work) }
    }
}
